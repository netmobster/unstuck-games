// Generate CATALOGUE_AUDIT.md from data/catalogue.json. Usage: node boop-remote/scripts/audit.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { CATEGORIES, STATUSES, TYPE_LABELS } from '../src/schema.js';

const root = new URL('../', import.meta.url);
const { records, generated, safety } = JSON.parse(readFileSync(new URL('data/catalogue.json', root), 'utf8'));
const count = (f) => records.reduce((o, r) => { const k = f(r); o[k] = (o[k] || 0) + 1; return o; }, {});
const table = (head, obj, label = k => k) => `| ${head} | Records |\n|---|---|\n` + Object.entries(obj).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| ${label(k)} | ${v} |`).join('\n');
const sources = records.flatMap(r => r.sources);
const srcTypes = sources.reduce((o, s) => { o[s.type] = (o[s.type] || 0) + 1; return o; }, {});
const opened = sources.filter(s => s.accessible !== false).length;
const list = (rs) => rs.map(r => `- **${r.name}** (\`${r.id}\`): ${r.watchOuts[0]}`).join('\n') || '- none';
const withPay = records.filter(r => r.compensation.min != null || r.compensation.max != null);
const payBasis = withPay.reduce((o, r) => { o[r.compensation.basis] = (o[r.compensation.basis] || 0) + 1; return o; }, {});

const md = `# Catalogue audit

Generated by \`scripts/audit.mjs\` from \`data/catalogue.json\` (built ${generated}). Re-run after any data change.

## Headline

- **${records.length} records**: ${records.filter(r => r.type !== 'category').length} specific routes and ${records.filter(r => r.type === 'category').length} "kind of work" category records.
- **${records.filter(r => !['rejected', 'not_currently_open'].includes(r.status)).length} can be recommended.** ${records.filter(r => r.status === 'rejected').length} are rejected and ${records.filter(r => r.status === 'not_currently_open').length} are closed; these stay in the data so the reasons are kept, but the app never ranks them.
- **0 records claim \`applications_open_confirmed\`.** No official page could be opened from the research environment (see RESEARCH_METHODOLOGY.md). Every status is therefore conservative.
- **Sources:** ${sources.length} citations, of which ${opened} were opened directly (job postings read through a job-board connector). The rest are search-engine summaries of the cited pages and are marked \`accessible: false\`.
- **${records.filter(r => r.applyUrl).length} direct application links.** No sign-up page was opened, so none was published (careers-page URLs from search results are kept in each record's sources). Next steps link to official homepages.
- **Pay:** ${withPay.length} records carry figures (basis: ${Object.entries(payBasis).map(([k, v]) => `${k} ${v}`).join(', ')}). ${records.filter(r => r.compensation.currency === 'unstated').length} were published without a currency and are shown as "currency not stated", never assumed to be USD.
- **${records.filter(r => r.audience && r.audience.length).length} records are limited to a specific group**, such as youth, students, assistive-technology users or Indigenous-language speakers. They're labelled and only reach the shortlist if liked.
- **Safety guidance:** ${safety.length} official Canadian job-scam sources power the About page.

## By category

${table('Category', count(r => r.category), k => CATEGORIES[k])}

## By verification status

${table('Status', count(r => r.status), k => `\`${k}\`: ${STATUSES[k]}`)}

## By type

${table('Type', count(r => r.type), k => TYPE_LABELS[k])}

## Evidence strength and Canadian eligibility

${table('Evidence strength', count(r => r.evidenceStrength))}

${table('Canada eligibility', count(r => r.geography.canadaEligibility))}

## Source types

| Source type | Citations |
|---|---|
${Object.entries(srcTypes).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| ${k} | ${v} |`).join('\n')}

## Records that need attention

### Stale (needs re-checking)
${list(records.filter(r => r.status === 'stale_needs_recheck'))}

### Uncertain
${list(records.filter(r => r.status === 'uncertain'))}

### Waitlist or little work reported
${list(records.filter(r => r.status === 'waitlist_or_no_work_guarantee'))}

### Closed
${list(records.filter(r => r.status === 'not_currently_open'))}

### Rejected
${list(records.filter(r => r.status === 'rejected'))}

### Weak evidence
${records.filter(r => r.evidenceStrength === 'weak').map(r => `- ${r.name} (\`${r.id}\`)`).join('\n')}

## Coverage gaps

The research search budget ran out before these were researched. They are gaps, not judgements:

- **Customer operations:** appointment setting, ecommerce order processing, remote customer service at Canadian banks, telcos and airlines, and a virtual-assistant category record. TELUS, Teleperformance, Amazon, Boldly, Time Etc and Arise were looked at and dropped for thin or conflicting evidence.
- **Creative and production:** social media management, captioning and editing, podcast support, digital asset tagging. **No records in this category.**
- **Freelance and microbusiness:** the "digital help for local small businesses" and "spreadsheet/data cleanup" category records were dropped because no citable source could be reached.
- **Language and writing:** content and product-description writing; a negative-signal pass for Welocalize.
- **Programs:** Youth Employment and Skills Strategy, Opportunities Fund for Persons with Disabilities, Canada Training Credit, OSAP micro-credentials.
- **Research participation:** Maru Voice Canada; paid study pools at other Ontario universities.
- **Geography:** Canada-first throughout. Nothing was checked for other countries, and the app says so.

Detailed per-family ledgers, including dropped candidates and open questions, are in \`research/ledger_*.md\`. Every automated policy change to the agents' data is listed in \`research/normalization_log.md\`.
`;
writeFileSync(new URL('CATALOGUE_AUDIT.md', root), md);
console.log('wrote CATALOGUE_AUDIT.md');
